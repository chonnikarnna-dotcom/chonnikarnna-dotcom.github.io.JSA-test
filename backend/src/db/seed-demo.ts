const H = 3600_000;
const inHours = (h: number) => new Date(Date.now() + h * H);

export function samplePdf(title = 'Supporting document'): Promise<Buffer> {
  return new Promise((resolve) => {
    const doc = new PDFDocument({ size: 'A4' });
    const chunks: Buffer[] = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.fontSize(16).text(title).fontSize(10).text('Sample attachment generated by the development seed.');
    doc.end();
  });
}

async function ids() {
  const area = async (code: string) => (await db.select().from(s.factoryAreas).where(eq(s.factoryAreas.code, code)))[0].id;
  const jt = async (code: string) => (await db.select().from(s.jobTypes).where(eq(s.jobTypes.code, code)))[0].id;
  const pt = async (code: string) => (await db.select().from(s.permitTypes).where(eq(s.permitTypes.code, code)))[0].id;
  const user = async (un: string) => (await loadAuthUser((await db.select().from(s.users).where(eq(s.users.username, un)))[0].id))!;
  return { area, jt, pt, user };
}

const hz = (hazard: string, consequence: string, i: [number, number], existing: string, additional: string, owner: string, r: [number, number]) => ({
  hazard, consequence, initialSeverity: i[0], initialLikelihood: i[1], existingControls: existing, additionalControls: additional,
  controlOwner: owner, residualSeverity: r[0], residualLikelihood: r[1],
});

export async function seedDemoJsas() {
  const existing = await db.select().from(s.jsas).limit(1);
  if (existing.length) { console.log('Demo JSAs already present — skipped.'); return; }
  const { area, jt, pt, user } = await ids();
  const [somchai, c1, c2, ao1, ao2, so1] = await Promise.all(['somchai', 'contractor1', 'contractor2', 'areaowner1', 'areaowner2', 'safety1'].map(user));

  const base = (o: Partial<DraftInput>): DraftInput => ({
    jobTitle: '', jobDescription: '', contactPhone: '081-234-5678', exactLocation: '', workerCount: 2, supervisorName: 'Supervisor on duty',
    supervisorPhone: '081-111-2222', emergencyContactName: 'Plant Security / Emergency Response Team', emergencyContactPhone: '1199',
    ppeRequired: ['SAFETY_HELMET', 'SAFETY_SHOES', 'SAFETY_GLASSES'], steps: [], permits: [], ...o,
  } as DraftInput);

  const approveAll = async (id: string, verifyPermits = true) => {
    for (const reviewer of [ao1, ao2, so1]) {
      const det = await jsa.getDetail(reviewer, id).catch(() => null);
      if (!det?.permissions.review) continue;
      await db.transaction((t) => reviewTask(t, reviewer, det.permissions.review!.taskId, 'APPROVE', {
        versionId: det.permissions.review!.versionId, comment: 'Reviewed — controls adequate.',
        verifiedPermitRefIds: verifyPermits ? det.content.permits.map((p) => p.id!) : [],
      }));
    }
  };

  // 1. Contractor hot work — fully approved
  const hot = await jsa.createDraft(c1, base({
    jobTitle: 'Weld repair of conveyor support frame — Bottling Line 1',
    jobDescription: 'Cut and re-weld cracked support bracket on the bottle conveyor between filler and labeller. Line stopped and isolated during work.',
    areaId: await area('A-BTL1'), exactLocation: 'Conveyor section C-12, between filler and labeller', jobTypeId: await jt('WELDING'),
    plannedStart: inHours(20), plannedEnd: inHours(28), workerCount: 3, ppeRequired: ['SAFETY_HELMET', 'SAFETY_SHOES', 'FACE_SHIELD', 'GLOVES'],
    permits: [
      { permitTypeId: await pt('HOT_WORK'), referenceNo: 'HW-2026-0412', answers: { fire_watch: true, combustibles_removed: true, extinguisher: true }, notes: 'Permit issued by Maintenance' },
      { permitTypeId: await pt('LOTO'), referenceNo: 'LOTO-BTL1-087', answers: { isolation_points: true, zero_energy: true } },
    ],
    steps: [
      { activity: 'Stop line, apply LOTO on conveyor drive and filler interlock', hazards: [hz('Unexpected start-up of conveyor', 'Crushing / amputation of hands', [5, 3], 'Line stop procedure', 'Personal locks on MCC isolator, try-start verification', 'Maintenance supervisor', [5, 1])] },
      { activity: 'Remove guarding and cut damaged bracket with angle grinder', hazards: [
        hz('Sparks and hot metal near PET preforms and cartons', 'Fire', [4, 3], 'Fire extinguisher on site', 'Fire blankets, remove combustibles within 10 m, fire watch', 'Contractor foreman', [4, 1]),
        hz('Grinder kickback / flying particles', 'Eye and hand injury', [3, 3], 'Grinder guard fitted', 'Face shield, cut-resistant gloves', 'Contractor foreman', [3, 1]),
      ] },
      { activity: 'Weld new bracket, reinstall guarding, remove LOTO and test run', hazards: [hz('Welding fumes and UV radiation', 'Respiratory irritation, arc eye', [3, 3], 'Local exhaust fan', 'Welding screen, respirator', 'Contractor foreman', [2, 2])] },
    ],
  }));
  await jsa.submit(c1, hot.id, { declarationAccepted: true, language: 'th' });
  await approveAll(hot.id);

  // 2. Employee electrical work — pending Area Owner
  const elec = await jsa.createDraft(somchai, base({
    jobTitle: 'Replace motor starter of capper drive — Bottling Line 2',
    jobDescription: 'Replace faulty contactor and overload relay in MCC panel for capper drive motor (400 V).',
    areaId: await area('A-BTL2'), exactLocation: 'MCC room, panel MCC-2B', jobTypeId: await jt('MAINT_ELEC'), plannedStart: inHours(30), plannedEnd: inHours(34),
    permits: [{ permitTypeId: await pt('ELECTRICAL'), referenceNo: 'EL-2026-0099', answers: { qualified: true, voltage_level: '400 V AC MCC' } }],
    steps: [
      { activity: 'Isolate and lock out MCC-2B feeder, verify absence of voltage', hazards: [hz('Contact with live conductors', 'Electric shock / arc flash burns', [5, 3], 'Insulated tools', 'Arc-rated PPE, voltage tester proved before/after', 'Electrical supervisor', [5, 1])] },
      { activity: 'Replace contactor and overload relay, re-terminate cables', hazards: [hz('Incorrect termination', 'Equipment damage / fire on re-energising', [3, 2], 'Wiring diagram', 'Second-person check of terminations', 'Electrical supervisor', [2, 1])] },
    ],
  }));
  await jsa.submit(somchai, elec.id, { declarationAccepted: true, language: 'th' });

  // 3. Contractor confined space — pending Safety Officer
  const cs = await jsa.createDraft(c2, base({
    jobTitle: 'Internal cleaning and inspection of syrup mixing tank T-03',
    jobDescription: 'Enter emptied syrup tank T-03 to clean residue and inspect agitator blades and welds.',
    areaId: await area('A-SYRUP'), exactLocation: 'Syrup room, tank T-03 manway', jobTypeId: await jt('CLEANING'), plannedStart: inHours(44), plannedEnd: inHours(52), workerCount: 4,
    ppeRequired: ['SAFETY_HELMET', 'SAFETY_SHOES', 'HARNESS', 'RESPIRATOR', 'GLOVES'],
    permits: [
      { permitTypeId: await pt('CONFINED_SPACE'), referenceNo: 'CSE-2026-021', answers: { gas_test: true, standby_person: true, rescue_plan: 'RP-SYR-03' } },
      { permitTypeId: await pt('LOTO'), referenceNo: 'LOTO-SYR-014', answers: { isolation_points: true, zero_energy: true } },
    ],
    steps: [
      { activity: 'Isolate agitator, CIP and product lines (blind / disconnect)', hazards: [hz('Agitator start or CIP chemical ingress', 'Fatal injury / chemical burns', [5, 3], 'LOTO procedure', 'Physical disconnection of CIP line, blank flanges', 'Area supervisor', [5, 1])] },
      { activity: 'Ventilate tank, perform gas test, enter with standby person', hazards: [hz('Oxygen deficiency / CO₂ pockets', 'Asphyxiation', [5, 3], 'Gas detector', 'Continuous forced ventilation and personal 4-gas monitors', 'Contractor supervisor', [5, 1])] },
      { activity: 'Clean residue and inspect agitator', hazards: [hz('Slippery tank floor', 'Fall injury', [2, 4], 'Anti-slip boots', 'Rinse residue before entry', 'Contractor supervisor', [2, 2])] },
    ],
  }));
  const pdf = await samplePdf('Confined space entry permit CSE-2026-021');
  const att = await uploadAttachment(c2, cs.id, { originalname: 'CSE-2026-021-permit.pdf', mimetype: 'application/pdf', buffer: pdf, size: pdf.length } as Express.Multer.File, 'WORK_PERMIT');
  const csDetail = await jsa.getDetail(c2, cs.id);
  const csInput = { ...(await import('../services/jsa-content')).contentToInput(csDetail.content) };
  csInput.permits = csInput.permits.map((p, i) => (i === 0 ? { ...p, attachmentId: att.id } : p));
  await jsa.updateDraft(c2, cs.id, csInput);
  await jsa.submit(c2, cs.id, { declarationAccepted: true, language: 'th' });
  const csAo = await jsa.getDetail(ao1, cs.id);
  await db.transaction((t) => reviewTask(t, ao1, csAo.permissions.review!.taskId, 'APPROVE', { versionId: csAo.permissions.review!.versionId, comment: 'Production will drain and hand over tank at 08:00.' }));

  // 4. Work at height — returned for revision
  const roof = await jsa.createDraft(somchai, base({
    jobTitle: 'Repair roof sheet leak above Bottling Line 1',
    jobDescription: 'Replace two damaged roof sheets and reseal gutter joint.',
    areaId: await area('A-ROOF'), exactLocation: 'Roof grid R4–R5', jobTypeId: await jt('CIVIL'), plannedStart: inHours(50), plannedEnd: inHours(58),
    permits: [{ permitTypeId: await pt('WORK_AT_HEIGHT'), referenceNo: 'WAH-2026-031', answers: { fall_protection: true, scaffold_tagged: true } }],
    steps: [{ activity: 'Access roof via fixed ladder and walk to grid R4', hazards: [hz('Falling through fragile roof sheets', 'Fatality', [5, 3], 'Harness', 'Crawling boards and lifeline', 'Maintenance supervisor', [5, 2])] }],
  }));
  await jsa.submit(somchai, roof.id, { declarationAccepted: true, language: 'th' });
  const roofAo = await jsa.getDetail(ao1, roof.id);
  await db.transaction((t) => reviewTask(t, ao1, roofAo.permissions.review!.taskId, 'RETURN', { versionId: roofAo.permissions.review!.versionId, comment: 'Please add a step for protecting the line below from falling objects (barricade the area under R4–R5).' }));

  // 5. Excavation in Plant B — rejected
  const exc = await jsa.createDraft(c1, base({
    jobTitle: 'Excavate trench for new wastewater pipe',
    jobDescription: 'Excavate 1.8 m deep trench, 20 m long, beside equalisation tank.',
    areaId: await area('B-WWT'), exactLocation: 'East side of equalisation tank', jobTypeId: await jt('CIVIL'), plannedStart: inHours(70), plannedEnd: inHours(100), workerCount: 5,
    permits: [{ permitTypeId: await pt('EXCAVATION'), referenceNo: 'EXC-2026-007', answers: { utilities_located: true } }],
    steps: [{ activity: 'Excavate trench with backhoe', hazards: [hz('Trench collapse', 'Burial / fatality', [5, 4], 'Spotter', 'Trench box', 'Contractor foreman', [5, 2])] }],
  }));
  await jsa.submit(c1, exc.id, { declarationAccepted: true, language: 'th' });
  const excAo = await jsa.getDetail(ao2, exc.id);
  await db.transaction((t) => reviewTask(t, ao2, excAo.permissions.review!.taskId, 'REJECT', { versionId: excAo.permissions.review!.versionId, comment: 'Project scope changed — trench route will be redesigned. Submit a new JSA once drawings are issued.' }));

  // 6. Draft
  await jsa.createDraft(somchai, base({ jobTitle: 'Replace bearing on boiler feed pump P-2', areaId: await area('A-BOILER'), jobTypeId: await jt('MAINT_MECH') }));

  // 7. Completed job
  const lift = await jsa.createDraft(somchai, base({
    jobTitle: 'Relocate pallet racking bay 12 using forklift',
    jobDescription: 'Dismantle and relocate one bay of pallet racking within the finished goods warehouse.',
    areaId: await area('B-WH'), exactLocation: 'Aisle 12', jobTypeId: await jt('LIFTING'), plannedStart: inHours(-1), plannedEnd: inHours(6),
    permits: [{ permitTypeId: await pt('LIFTING'), referenceNo: 'LFT-2026-018', answers: { lift_plan: true, certified_operator: true } }],
    steps: [{ activity: 'Lower and move racking frames with forklift', hazards: [hz('Racking frame toppling', 'Crush injury', [4, 2], 'Certified forklift operator', 'Exclusion zone with barriers and banksman', 'Warehouse supervisor', [4, 1])] }],
  }));
  await jsa.submit(somchai, lift.id, { declarationAccepted: true, language: 'en' });
  await approveAll(lift.id);
  await jsa.complete(somchai, lift.id, 'Racking relocated and inspected; area returned to warehouse.');
  console.log('Demo JSAs created.');
}
